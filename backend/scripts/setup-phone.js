#!/usr/bin/env node
/**
 * Thunai — Real Phone Call Setup Wizard
 *
 * This script:
 * 1. Checks prerequisites (Node, ngrok, Twilio creds)
 * 2. Starts ngrok tunnel to expose port 4000
 * 3. Automatically configures the Twilio webhook
 * 4. Starts the backend
 * 5. Gives you the phone number to call
 *
 * Usage:
 *   node scripts/setup-phone.js
 */

import { execSync, spawn } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createInterface } from 'node:readline';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const ENV_FILE = join(ROOT, '.env');

const rl = createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise(r => rl.question(q, r));

function log(msg) { console.log(`\n  🔧 ${msg}`); }
function ok(msg)  { console.log(`  ✅ ${msg}`); }
function warn(msg){ console.log(`  ⚠️  ${msg}`); }
function err(msg) { console.log(`  ❌ ${msg}`); }

async function main() {
  console.log(`
  ╔══════════════════════════════════════════════════╗
  ║     துணை · THUNAI — Real Phone Call Setup        ║
  ║     Tamil Voice-First Scheme Navigator           ║
  ╚══════════════════════════════════════════════════╝
  `);

  // ── Step 1: Check if .env exists with Twilio creds ──
  log('Checking Twilio credentials...');
  let envContent = '';
  if (existsSync(ENV_FILE)) {
    envContent = readFileSync(ENV_FILE, 'utf8');
  }

  const sid = envContent.match(/TWILIO_ACCOUNT_SID=(.+)/)?.[1]?.trim();
  const token = envContent.match(/TWILIO_AUTH_TOKEN=(.+)/)?.[1]?.trim();
  const phoneFrom = envContent.match(/TWILIO_PHONE_NUMBER=(.+)/)?.[1]?.trim();

  if (!sid || !token || !phoneFrom || sid.startsWith('your_') || sid === '') {
    warn('Twilio credentials not found or incomplete in backend/.env');
    console.log(`
  ┌──────────────────────────────────────────────────────┐
  │  You need a Twilio account to receive real calls.    │
  │                                                      │
  │  1. Go to https://www.twilio.com/try-twilio          │
  │  2. Sign up (free trial gives you $15 credit)        │
  │  3. Verify your personal phone number                │
  │  4. Get a trial phone number (Twilio assigns one     │
  │     automatically, or buy one for ~$1/month)         │
  │  5. Copy your credentials from the Twilio Console:   │
  │     https://console.twilio.com                       │
  │                                                      │
  │  ⚡ Trial accounts can only call verified numbers.    │
  │     Upgrade (~$20) to call any number.               │
  └──────────────────────────────────────────────────────┘
    `);

    const inputSid = await ask('  Enter TWILIO_ACCOUNT_SID: ');
    const inputToken = await ask('  Enter TWILIO_AUTH_TOKEN: ');
    const inputPhone = await ask('  Enter TWILIO_PHONE_NUMBER (e.g. +1234567890): ');

    if (!inputSid || !inputToken || !inputPhone) {
      err('All three values are required. Exiting.');
      process.exit(1);
    }

    // Write/update .env
    const newEnv = `# Thunai Environment — Generated by setup-phone.js
PORT=4000
TWILIO_ACCOUNT_SID=${inputSid}
TWILIO_AUTH_TOKEN=${inputToken}
TWILIO_PHONE_NUMBER=${inputPhone}
NODE_ENV=development
`;
    writeFileSync(ENV_FILE, newEnv, 'utf8');
    ok('Saved credentials to backend/.env');
  } else {
    ok(`Twilio credentials found: SID=${sid.slice(0,8)}... Phone=${phoneFrom}`);
  }

  // Reload env
  const finalEnv = readFileSync(ENV_FILE, 'utf8');
  const finalSid = finalEnv.match(/TWILIO_ACCOUNT_SID=(.+)/)?.[1]?.trim();
  const finalToken = finalEnv.match(/TWILIO_AUTH_TOKEN=(.+)/)?.[1]?.trim();
  const finalPhone = finalEnv.match(/TWILIO_PHONE_NUMBER=(.+)/)?.[1]?.trim();

  // ── Step 2: Start ngrok ──
  log('Starting ngrok tunnel on port 4000...');

  let ngrokUrl = null;
  const ngrok = spawn('ngrok', ['http', '4000', '--log', 'stdout', '--log-format', 'json'], {
    stdio: ['ignore', 'pipe', 'pipe'],
    shell: true,
  });

  // Wait for ngrok to produce the public URL
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('ngrok timeout')), 15000);
    ngrok.stdout.on('data', (data) => {
      const lines = data.toString().split('\n');
      for (const line of lines) {
        try {
          const obj = JSON.parse(line);
          if (obj.url && obj.url.startsWith('https://')) {
            ngrokUrl = obj.url;
            clearTimeout(timeout);
            resolve();
          }
        } catch { /* not JSON, skip */ }
      }
    });
    ngrok.stderr.on('data', (data) => {
      const text = data.toString();
      if (text.includes('ERR_NGROK')) {
        clearTimeout(timeout);
        reject(new Error(`ngrok error: ${text}`));
      }
    });
  });

  ok(`ngrok tunnel: ${ngrokUrl}`);

  // ── Step 3: Configure Twilio webhook ──
  log('Configuring Twilio webhook...');

  const webhookUrl = `${ngrokUrl}/ivr/voice`;

  try {
    // Use Twilio REST API to find the phone number SID and update its voice URL
    const authHeader = Buffer.from(`${finalSid}:${finalToken}`).toString('base64');

    // List incoming phone numbers
    const listRes = await fetch(
      `https://api.twilio.com/2010-04-01/Accounts/${finalSid}/IncomingPhoneNumbers.json?PhoneNumber=${encodeURIComponent(finalPhone)}`,
      { headers: { 'Authorization': `Basic ${authHeader}` } }
    );

    if (!listRes.ok) {
      const errBody = await listRes.text();
      throw new Error(`Twilio API error: ${listRes.status} ${errBody}`);
    }

    const listData = await listRes.json();
    const numbers = listData.incoming_phone_numbers || [];

    if (numbers.length === 0) {
      warn(`Phone number ${finalPhone} not found in your Twilio account.`);
      warn(`You may need to buy a number at https://console.twilio.com/develop/phone-numbers`);
      warn(`Manually set the Voice webhook to: ${webhookUrl}`);
    } else {
      const phoneSid = numbers[0].sid;

      // Update the voice webhook URL
      const updateRes = await fetch(
        `https://api.twilio.com/2010-04-01/Accounts/${finalSid}/IncomingPhoneNumbers/${phoneSid}.json`,
        {
          method: 'POST',
          headers: {
            'Authorization': `Basic ${authHeader}`,
            'Content-Type': 'application/x-www-form-urlencoded',
          },
          body: `VoiceUrl=${encodeURIComponent(webhookUrl)}&VoiceMethod=POST`,
        }
      );

      if (updateRes.ok) {
        ok(`Twilio webhook set to: ${webhookUrl}`);
      } else {
        const errText = await updateRes.text();
        warn(`Could not auto-configure webhook: ${errText}`);
        warn(`Manually set Voice URL to: ${webhookUrl}`);
      }
    }
  } catch (e) {
    warn(`Auto-configuration failed: ${e.message}`);
    console.log(`
  ┌─────────────────────────────────────────────────────┐
  │  Manually configure your Twilio number:             │
  │                                                     │
  │  1. Go to: https://console.twilio.com               │
  │  2. Phone Numbers → Manage → Active Numbers         │
  │  3. Click your number                               │
  │  4. Under "Voice & Fax" → "A CALL COMES IN":       │
  │     URL: ${webhookUrl.padEnd(42)}│
  │     Method: POST                                    │
  │  5. Click Save                                      │
  └─────────────────────────────────────────────────────┘
    `);
  }

  // ── Step 4: Update PUBLIC_BASE_URL in .env ──
  let updatedEnv = readFileSync(ENV_FILE, 'utf8');
  if (updatedEnv.includes('PUBLIC_BASE_URL=')) {
    updatedEnv = updatedEnv.replace(/PUBLIC_BASE_URL=.*/g, `PUBLIC_BASE_URL=${ngrokUrl}`);
  } else {
    updatedEnv += `\nPUBLIC_BASE_URL=${ngrokUrl}\n`;
  }
  writeFileSync(ENV_FILE, updatedEnv, 'utf8');

  // ── Done ──
  console.log(`
  ╔══════════════════════════════════════════════════════╗
  ║                  🎉 READY!                           ║
  ╠══════════════════════════════════════════════════════╣
  ║                                                      ║
  ║   📞 Dial this number to talk to Thunai:             ║
  ║      ${finalPhone.padEnd(45)}║
  ║                                                      ║
  ║   🌐 Backend:   http://localhost:4000                ║
  ║   🌐 Public:    ${ngrokUrl.padEnd(33)}║
  ║   🌐 Webhook:   ${webhookUrl.slice(0, 33).padEnd(33)}║
  ║   🌐 Dashboard: http://localhost:5173                ║
  ║   🌐 API Docs:  http://localhost:4000/api/docs       ║
  ║                                                      ║
  ║   Now restart the backend in another terminal:       ║
  ║     cd backend && node src/server.js                 ║
  ║                                                      ║
  ║   Then call ${finalPhone} from your phone!${' '.repeat(Math.max(0, 13 - finalPhone.length))}║
  ║                                                      ║
  ║   ⚠️  Trial accounts: only verified numbers can call ║
  ║   Press Ctrl+C to stop ngrok when done.              ║
  ╚══════════════════════════════════════════════════════╝
  `);

  rl.close();

  // Keep ngrok running
  process.on('SIGINT', () => {
    ngrok.kill();
    process.exit(0);
  });

  // Wait forever (ngrok stays running)
  await new Promise(() => {});
}

main().catch(e => {
  err(e.message);
  process.exit(1);
});

